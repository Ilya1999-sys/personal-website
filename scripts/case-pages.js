const imagePath = (type, index) => `/images/cases/${type === "loginom" ? "loginom" : "event-visual"}/${type === "loginom" ? "loginom" : "event"}-${String(index).padStart(2, "0")}.png?v=20261024-originals`;
const escape = (text = "") => String(text).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

function imageGrid(type, indices, label, extraClass = "") {
  return `<div class="case-detail__gallery ${extraClass}" aria-label="${escape(label)}">${indices.map((index, position) => `<figure><img src="${imagePath(type, index)}" alt="${escape(label)} — изображение ${position + 1}" loading="lazy" decoding="async" /></figure>`).join("")}</div>`;
}

function textCards(content) {
  return `<div class="case-detail__text-grid">${[
    ["Проблема", content.problem],
    ["Задача", content.task],
    ["Процесс работы", content.process],
  ].map(([label, body]) => `<article class="case-detail__text-card"><h3>${label}</h3><p>${escape(body)}</p></article>`).join("")}</div>`;
}

function mediaSection(type, title, indices, extraClass = "") {
  return `<section class="case-detail__media"><h3>${escape(title)}</h3>${imageGrid(type, indices, title, extraClass)}</section>`;
}

function resultSection(copy) {
  return `<section class="case-detail__result"><h3>Итог</h3><p>${escape(copy)}</p></section>`;
}

function taskSection(task, index) {
  return `<section class="case-detail__task" aria-labelledby="loginom-task-${index + 1}">
    <div class="case-detail__task-heading"><span>Задача</span><h2 id="loginom-task-${index + 1}">${escape(task.title)}</h2></div>
    ${textCards(task)}
    ${task.prototypes?.length ? mediaSection("loginom", index >= 4 ? "Прототипы и исследование" : "Прототипы", task.prototypes) : ""}
    ${mediaSection("loginom", "Итоговый дизайн", task.design)}
    ${resultSection(task.result)}
  </section>`;
}

function cover(header, title, intro) {
  return `<section class="case-detail__cover panel">${header()}<div class="case-detail__intro"><h1 class="no-nbsp">${escape(title)}</h1><p>${escape(intro)}</p></div></section>`;
}

